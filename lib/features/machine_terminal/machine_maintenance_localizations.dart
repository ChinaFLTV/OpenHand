  return seconds >= 3600
      ? l.maintenanceTimeoutHours('${seconds ~/ 3600}')
      : seconds >= 60
      ? l.maintenanceTimeoutMinutes('${seconds ~/ 60}')
      : l.maintenanceTimeoutSeconds('$seconds');
}
