final _egressRegionCodes = {
  for (final entry in machineEgressRegionNames.entries)
    for (final name in entry.value) name.toLowerCase(): entry.key,
};

/// 地理名称随界面语言切换，地址、组织、运营商及未知地名保留数据源原值。
String maintenanceEgressValue(
  BuildContext context,
  MachineEgressReport report,
  String field,
  String value,
) {
  final l10n = AppLocalizations.of(context)!;
  if (value == 'true') return l10n.maintenanceHealthParsedYes;
  if (value == 'false') return l10n.maintenanceHealthParsedNo;
  if (field != '国家或地区' && field != '洲') return value;
  final codeLabel = field == '洲' ? '洲代码' : '国家代码';
  var code = '';
  for (final row in report.groups['地理位置'] ?? const <List<String>>[]) {
    if (row[0] == codeLabel) {
      code = row[1].toUpperCase();
      break;
    }
  }
  if (field == '洲') {
    code =
        const {
          'AF': '002',
          'NA': '003',
          'SA': '005',
          'OC': '009',
          'AS': '142',
          'EU': '150',
          'AN': 'AQ',
        }[code] ??
        code;
  }
  final names =
      machineEgressRegionNames[code] ??
      machineEgressRegionNames[_egressRegionCodes[value.trim().toLowerCase()]];
  if (names == null) return value;
  final locale = Localizations.localeOf(context);
  final index = switch (locale.languageCode) {
    'zh' =>
      locale.scriptCode == 'Hant' ||
              const {'TW', 'HK', 'MO'}.contains(locale.countryCode)
          ? 2
          : 1,
    'de' => 3,
    'fr' => 4,
    'ja' => 5,
    _ => 0,
  };
  return names[index];
}

String maintenanceContainerOperationError(BuildContext context, Object error) {
  final l = AppLocalizations.of(context)!;
  if (error is TimeoutException) {
    return '${l.maintenanceContainerTimeoutTitle} · ${l.maintenanceContainerTimeoutHelp}';
  }
  if (error is FormatException) return l.maintenanceContainerConfigInvalid;
  if (error is! MachineContainerConfigException) return '$error';
  return switch (error.code) {
    'incomplete' => l.maintenanceContainerRunIncomplete(error.details),
    'unsupported' => l.maintenanceContainerRunUnsupported,
    'form' =>
      '${l.maintenanceResourceValidation} · ${maintenanceLabel(context, error.details)}',
    'resourceUnsupported' => l.maintenanceResourceUnsupported,
    'image' => l.maintenanceContainerImageMissing,
    'stale' => l.maintenanceContainerIdentityChanged,
    _ => l.maintenanceContainerConfigInvalid,
  };
}

