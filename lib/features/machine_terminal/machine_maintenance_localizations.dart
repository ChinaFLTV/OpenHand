        final field = RegExp(
          r'^(\s*)([A-Za-z_]+)(\[\d+\]| #\d+)?(\s*[:=].*|\s*)$',
        ).firstMatch(line);
        if (field != null && fields.containsKey(field[2])) {
          return '${field[1]}${maintenanceLabel(context, fields[field[2]]!)}${field[3] ?? ''}${field[4]}';
        }
        if (RegExp(
          r'^\s*(Destination\s+Gateway|Proto(?:/ID)?\s+|Address\s+Type)',
        ).hasMatch(line)) {
          for (final entry in headings.entries) {
            line = line.replaceAllMapped(
              RegExp('(?<![A-Za-z])${RegExp.escape(entry.key)}(?![A-Za-z])'),
              (_) => maintenanceLabel(context, entry.value),
            );
          }
        }
        return line;
      })
      .join('\n');
}

