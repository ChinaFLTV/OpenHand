          'Routing tables',
          'DNS configuration',
          'Active Internet connections',
          'Active Multipath Internet connections',
          'Active LOCAL (UNIX) domain sockets',
        ].contains(trimmed)) {
          return maintenanceLabel(context, trimmed);
        }
        final field = RegExp(
          r'^(\s*)([A-Za-z_]+)(\[\d+\]| #\d+)?(\s*[:=].*|\s*)$',
        ).firstMatch(line);
        if (field != null && fields.containsKey(field[2])) {
          return '${field[1]}${maintenanceLabel(context, fields[field[2]]!)}${field[3] ?? ''}${field[4]}';
        }
        if (RegExp(
          r'^\s*(Destination\s+Gateway|Proto(?:/ID)?\s+|Address\s+Type)',
