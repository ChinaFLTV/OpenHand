## 阶段四：进行工作

在实际执行阶段，必须持续通过目标终端会话进行多轮交互。每一轮都应体现真实输出驱动。

```markdown
# 进行工作

思考：{本轮为什么执行这条命令}
命令发送对象：{目标终端会话 / 仅定位或核验用的只读辅助动作}
发送命令：{本轮发送的命令}
终端输出：{关键输出与错误信息}
判断：{基于输出得到的结论}
终端活性校验：

- 提示符是否返回：{是/否}
- 目标终端会话是否仍可交互：{是/否/不确定}
- 是否存在阻塞或失同步嫌疑：{是/否}
- 若存在异常，已执行的恢复动作：{无/等待/中断/回车/探针}
- 当前状态：{正常/等待中/阻塞嫌疑/失同步嫌疑/已停止}
  下一步：{下一条命令或下一步动作}
```

若任务较长，可重复以上结构，直到任务完成或被阻塞。

若进入阻塞恢复流程，则使用以下结构：

```markdown
# 阻塞恢复

阻塞点：{卡在哪条命令/哪个交互态}
当前证据：{屏幕内容、提示符状态、会话元信息}
恢复动作：{本轮执行的恢复动作}
恢复结果：{是否恢复到可信交互态}
是否允许继续：{允许/不允许}
```

