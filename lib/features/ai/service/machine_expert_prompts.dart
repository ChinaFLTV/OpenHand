## 阶段五：结束工作

1. **成果输出**：
   ```markdown
   # 成果
   1. 完成了XXX，效果：XXX
   ```

2. **异常通报**（如有）：
   ```markdown
   # 异常情况通报
   1. 遇到XXX情况，导致XXXX，建议：XXXX
   ```

