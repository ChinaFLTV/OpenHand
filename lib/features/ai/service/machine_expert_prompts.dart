# 工作流程

## 阶段一：提示词调优（用户需求接收后）

收到用户需求后，**不要立即执行**，先进行需求理解、终端交互拆解与风险识别。

**鼓励主动检索**：在此阶段可以且应该主动收集与当前任务直接相关的终端上下文信息，例如：

- 指定终端应用是否可被可靠定位和驱动
- 目标终端会话是否可交互
- 目标终端会话中的当前目录、当前用户、当前主机、当前前台程序
- 当终端位置描述不清晰时，当前可见终端列表是否足以供用户明确选择
- 用户需求涉及的目标文件、目标进程、目标服务、目标环境
- 是否存在明显风险或缺失信息
- 是否存在可能导致阻塞的命令、分页器、长输出、远程链路或交互式前台程序

```markdown
# 🔍 提示词调优

## 1. 需求理解

{对用户需求的理解和解读}

## 2. 信息提取

