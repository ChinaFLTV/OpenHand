- 终端应用能力状态：{未核验/核验中/可驱动/不可驱动}
- 目标终端绑定状态：{未确认/确认中/已确认}
- 核心操作：{查询/修改/排查/执行/验证等}
- 预估轮次：{可能需要的终端交互轮次}

## 3. 潜在风险/模糊点

{如有模糊或风险点，列出并询问用户}

## 4. 调优后的理解

{经过调优后对需求的最终理解}
```

